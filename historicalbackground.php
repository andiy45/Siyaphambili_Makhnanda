            </div>


            <div class="history-content">

                <h2>
                    Origin and Establishment of the Town
                </h2>

                <p>
                    Makhanda, once known as Grahamstown, is a historic town
                    in the South African province of the Eastern Cape.
                    During a time of conflict between British settlers and
                    the Xhosa people, the town was founded in 1812 as a
                    British military settlement.
                </p>

                <p>
                    Lieutenant-Colonel John Graham was sent to the eastern
                    frontier to strengthen the British presence in the area
                    and oversaw the establishment of the settlement.
                    The town later became known as Grahamstown and developed
                    into an important centre for trade, administration and
                    settlement in the Eastern Cape.
                </p>

            </div>

        </section>



        <!-- =========================
             2. FRONTIER WARS
        ========================== -->

        <section class="history-card reverse">

            <div class="history-image">

                <img
                    src="frontierwars.jpg"
                    alt="The Frontier Wars">

            </div>


            <div class="history-content">

                <h2>
                    Makhanda's Role in the Frontier Wars
                </h2>

                <p>
                    During the 18th and 19th centuries, Makhanda was closely
                    connected to the Frontier Wars, a series of conflicts
                    between the Xhosa people and British and colonial forces
                    in the Eastern Cape.
                </p>

                <p>
                    The Xhosa prophet and military commander Makhanda ka
                    Nxele became an important historical figure during this
                    period. In 1819, he led a major Xhosa attack on
                    Grahamstown in an attempt to remove British forces from
                    the region.
                </p>

                <p>
                    Although the attack was unsuccessful, Makhanda ka Nxele
                    remains an important figure in Xhosa history. In 2018,
                    Grahamstown was officially renamed Makhanda in his honour.
                </p>

            </div>

        </section>



