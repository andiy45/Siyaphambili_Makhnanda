                    Development of the Town
                </h2>

                <p>
                    After being founded as a military settlement, Makhanda
                    progressively grew into an important Eastern Cape town.
                    As the population increased, the town moved beyond its
                    original military purpose and developed into a centre
                    for commerce, government and education.
                </p>

                <p>
                    The establishment of churches, schools, businesses and
                    other public institutions contributed to the growth of
                    the town and surrounding communities.
                </p>

                <p>
                    Over time, these establishments helped shape Makhanda
                    into an important educational and cultural centre.
                </p>

            </div>

        </section>



